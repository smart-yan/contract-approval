"""关键词抽取（P7-3）。

职责边界
-------
::

    ParseResult  →  list[KeywordHit]

它只回答**一个问题**：

    **这份文档里出现了哪些主题词？**

它**不回答**：

* 某个词出现意味着什么风险（P8 的规则引擎的事）
* 这个词属于哪个维度、有多重要（不做 weight / category —— 没有消费者）
* 出现了几次（次数 = 命中条数，是派生量）

⚠️ **P7-3 ≠ P8 ``RuleType.KEYWORD``**

===========================  ==========================================
P7-3 Keyword Extraction      P8 ``RuleType.KEYWORD``
===========================  ==========================================
"文档里出现了什么主题词？"     "某条规则是否因关键词命中而触发风险？"
词典在 Agent 侧的代码常量里     关键词在 ``review_rule.expression`` 里（业务可配置）
作用域：全文档                  作用域：限定 ``target_clause_types``
输出：``(term, paragraph_index)``  输出：命中 / 未命中 + 风险项
===========================  ==========================================

**因此 P8 的规则引擎不得引用 ``state["keywords"]``** —— 两边各有自己的词表与判定，
混用就是两套会漂移的规则。同理，P7-3 不产出任何带风险含义的字段。

顺带划清与 P7-1 的边界：``ClauseType`` 的关键词表**只看条款的标题行**、产出的是
分类标签；这里的词表**扫描所有段落**、产出的是命中位置。两者作用域与输出都不同。

匹配规则
-------
1. 扫描**所有段落**（含 ``TABLE_ROW`` —— 付款计划、交付清单常写在表格里）
2. 词表里的每个词**独立**匹配；命中的是"这个词出现在这一段"
3. **同一 ``(term, paragraph_index)`` 只产出一条** —— 一段里出现三次也只算一次
4. 输出顺序：**段落顺序优先**，同段内按词表顺序 —— 确定、可复现

第 3 条是刻意的：下游要的是"这一段谈到了付款"，而不是词频。
要统计频次时由调用方自己数命中条数，不必在这里多存一个可能与命中列表不一致的字段。

已知行为（测试里固定）
--------------------
词表里若同时有 ``付款`` 与 ``预付款``，一段写「预付款 30%」会产出**两条**命中
（两个词各自命中）。这是"每个词独立匹配"的直接结果 —— 不做最长匹配抑制，
因为对"主题索引"来说，两个词同时出现本身就是有意义的信息。
"""

from __future__ import annotations

from app.schemas.document import ParseResult
from app.schemas.understanding import KeywordHit

# --------------------------------------------------------------------------- #
# 受控词表
#
# **只在这一处定义。** 选词标准：合同里常见、能说明"这一份合同谈到了什么"的主题词。
# 刻意不收过于宽泛的词（如单字「价」），它们会把噪声也扫进来。
# --------------------------------------------------------------------------- #
KEYWORD_LEXICON: tuple[str, ...] = (
    # ---- 金额与支付 ----
    "合同金额",
    "价款",
    "预付款",
    "尾款",
    "付款",
    "支付",
    "结算",
    "发票",
    "税率",
    # ---- 交付与验收 ----
    "交付",
    "交货",
    "验收",
    "检验",
    "测试",
    "部署",
    "上线",
    "工期",
    "进度",
    # ---- 违约与救济 ----
    "违约",
    "赔偿",
    "损失",
    "罚款",
    "解除",
    "终止",
    # ---- 保密与知识产权 ----
    "保密",
    "商业秘密",
    "知识产权",
    "著作权",
    "专利",
    "商标",
    "源代码",
    # ---- 争议与法律适用 ----
    "争议",
    "仲裁",
    "诉讼",
    "管辖",
    # ---- 数据与安全 ----
    "数据",
    "个人信息",
    "网络安全",
    # ---- 其他常见主题 ----
    "不可抗力",
    "质保",
    "售后",
    "培训",
    "保险",
    "变更",
    "转让",
    "分包",
)


def extract_keywords(parse_result: ParseResult) -> list[KeywordHit]:
    """扫描全部段落，返回主题词命中列表。

    **不抛异常**：没有命中就返回空列表，段落为空同样如此。
    输出顺序 = 段落顺序 → 同段内词表顺序。
    """
    hits: list[KeywordHit] = []

    for paragraph in parse_result.paragraphs:
        text = paragraph.text
        for term in KEYWORD_LEXICON:
            if term in text:
                # 每个 (term, paragraph_index) 只产出一条
                hits.append(KeywordHit(term=term, paragraph_index=paragraph.index))

    return hits


__all__ = ["KEYWORD_LEXICON", "extract_keywords"]
